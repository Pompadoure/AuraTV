#!/usr/bin/env python3
"""Emit Aura TV overrides for every core string that names the product "OwnTV".

Core (OwnTV_Core, a read-only dependency) owns all user-visible strings. This script reads its
`values*/*.xml` files and writes `app/src/main/res/values*/aura_brand_strings.xml`, which override the
same resource names with "OwnTV" replaced by "Aura TV". Only the product name is replaced; a string is
left alone (and listed by --report) when "OwnTV" is part of a URL, a path, a file name, an identifier or
an attribution sentence. The output is deterministic and committed like the other generated brand assets.

    python3 tools/brand/rebrand_strings.py --core /path/to/OwnTV_Core --res app/src/main/res
    python3 tools/brand/rebrand_strings.py --core /path/to/OwnTV_Core --res app/src/main/res --report

Without --core the CORE_SHA of the "Use OwnTV_Core source" step in .github/workflows/android.yml is
fetched read-only into a temporary directory.
"""
import argparse
import glob
import os
import re
import subprocess
import sys
import tempfile

BRAND = "Aura TV"
# Resources the app defines itself (app/src/main/res/values/strings.xml); never regenerate them.
ALWAYS_KEEP = {"app_name"}
NAME_RE = re.compile(r"OwnTV")
# The element kinds whose text can hold the product name.
ELEMENT_RE = re.compile(r"<(string|plurals|string-array)\b([^>]*)>(.*?)</\1>", re.S)
NAME_ATTR_RE = re.compile(r'\bname="([^"]+)"')
# "OwnTV" glued to something that makes it an identifier, path or address rather than the product name.
IDENT_BEFORE = re.compile(r"[/@._\\-]$|[A-Za-z0-9]$")
# Letters straight after the name are case suffixes in Basque, Turkish, Danish ("OwnTVra"): fine to keep.
IDENT_AFTER = re.compile(r"^_|^/|^\\(?!['\"nt])|^\.(?:own|tv|apk|json|db|zip)\b")
# Attribution and upstream references keep the original name (GPLv3 credit).
ATTRIBUTION_RE = re.compile(r"based on|fork of|forked from|originally|upstream|created by|credits?\b|licen[sc]e", re.I)
URL_RE = re.compile(r"https?://|github\.com|ahXN00|t\.me/|weblate", re.I)

HEADER = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- GENERATED by tools/brand/rebrand_strings.py - do not edit by hand. -->\n"
    '<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2" xmlns:tools="http://schemas.android.com/tools">\n'
)


def rename(text):
    """Replace the product name in [text]; None when it must stay as it is."""
    if URL_RE.search(text) or ATTRIBUTION_RE.search(text):
        return None
    out, last = [], 0
    for m in NAME_RE.finditer(text):
        before, after = text[: m.start()][-1:], text[m.end():][:6]
        if before and IDENT_BEFORE.search(before):
            # A letter right before ("TheOwnTV") or a path char: not the bare product name.
            return None
        if after and IDENT_AFTER.search(after):
            return None
        out.append(text[last : m.start()])
        out.append(BRAND)
        last = m.end()
    out.append(text[last:])
    return "".join(out)


def core_source(arg):
    if arg:
        return arg
    wf = open(os.path.join(os.path.dirname(__file__), "..", "..", ".github", "workflows", "android.yml"), encoding="utf8").read()
    sha = re.search(r"CORE_SHA:\s*([0-9a-f]{40})", wf).group(1)
    tmp = tempfile.mkdtemp(prefix="owntv-core-")
    subprocess.run(["git", "init", "-q", tmp], check=True)
    subprocess.run(["git", "-C", tmp, "fetch", "-q", "--depth", "1", "https://github.com/ahXN00/OwnTV_Core.git", sha], check=True)
    subprocess.run(["git", "-C", tmp, "checkout", "-q", "FETCH_HEAD"], check=True)
    return tmp


def app_defined(res, folder):
    """Resource names the app already defines in [folder]; redefining one would be a duplicate."""
    names = set()
    for f in glob.glob(os.path.join(res, folder, "*.xml")):
        if os.path.basename(f) == "aura_brand_strings.xml":
            continue
        for m in re.finditer(r'<(?:string|plurals|string-array)\b[^>]*\bname="([^"]+)"', open(f, encoding="utf8").read()):
            names.add(m.group(1))
    return names


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--core", help="path to an OwnTV_Core checkout")
    ap.add_argument("--res", default="app/src/main/res")
    ap.add_argument("--report", action="store_true", help="also list every string left unchanged")
    args = ap.parse_args()
    core = core_source(args.core)

    # folder -> {name: element xml}; later modules override earlier ones only if the name repeats.
    found, kept = {}, []
    files = sorted(glob.glob(os.path.join(core, "*", "src", "main", "res", "values*", "*.xml")))
    for f in files:
        folder = os.path.basename(os.path.dirname(f))
        for m in ELEMENT_RE.finditer(open(f, encoding="utf8").read()):
            kind, attrs, body = m.groups()
            if "OwnTV" not in body:
                continue
            nm = NAME_ATTR_RE.search(attrs)
            if not nm:
                continue
            name = nm.group(1)
            if name in ALWAYS_KEEP:
                continue
            new_body = rename(body)
            if new_body is None:
                kept.append((folder, name))
                continue
            found.setdefault(folder, {})[name] = f"    <{kind}{attrs}>{new_body}</{kind}>\n"

    written = 0
    for folder in sorted(found):
        taken = app_defined(args.res, folder)
        items = [(n, x) for n, x in sorted(found[folder].items()) if n not in taken]
        for n in found[folder]:
            if n in taken:
                kept.append((folder, n + " (app already defines it)"))
        path = os.path.join(args.res, folder, "aura_brand_strings.xml")
        if not items:
            if os.path.exists(path):
                os.remove(path)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf8", newline="\n") as out:
            out.write(HEADER + "".join(x for _, x in items) + "</resources>\n")
        written += len(items)
    # Drop files of folders that no longer have anything to override.
    for path in glob.glob(os.path.join(args.res, "values*", "aura_brand_strings.xml")):
        if os.path.basename(os.path.dirname(path)) not in found:
            os.remove(path)

    print(f"{written} overrides in {len(found)} locale folders; {len(kept)} left unchanged")
    if args.report:
        for folder, name in sorted(kept):
            print(f"  kept {folder}/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
